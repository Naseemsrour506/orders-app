create or replace function public.current_member_id() returns uuid
language sql stable security definer set search_path = public as $$
  select m.id
  from public.member_devices d
  join public.members m on m.id = d.member_id
  where d.auth_uid = auth.uid() and m.active
$$;

create or replace function public.current_role_name() returns public.member_role
language sql stable security definer set search_path = public as $$
  select m.role
  from public.member_devices d
  join public.members m on m.id = d.member_id
  where d.auth_uid = auth.uid() and m.active
$$;

create or replace function public.current_team_id() returns smallint
language sql stable security definer set search_path = public as $$
  select m.team_id
  from public.member_devices d
  join public.members m on m.id = d.member_id
  where d.auth_uid = auth.uid() and m.active
$$;

create or replace function public.is_manager() returns boolean
language sql stable as $$
  select coalesce(public.current_role_name() = 'manager', false)
$$;

create or replace function public.is_designer() returns boolean
language sql stable as $$
  select coalesce(public.current_role_name() = 'designer', false)
$$;

create or replace function public.today_il() returns date
language sql stable as $$
  select (now() at time zone 'Asia/Jerusalem')::date
$$;

-- הגרפיקאי רואה רק הזמנות שנשלחו אליו.
create or replace function public.designer_can_see(p_order_id bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select public.is_designer() and exists (
    select 1 from public.orders o
    where o.id = p_order_id and o.sent_to_designer_at is not null
  )
$$;

create or replace function public.require_manager() returns uuid
language plpgsql stable security definer set search_path = public as $$
declare
  v_id uuid := public.current_member_id();
begin
  if v_id is null or public.current_role_name() <> 'manager' then
    raise exception 'רק המנהל יכול לעשות את זה' using errcode = '42501';
  end if;
  return v_id;
end;
$$;

create or replace function public.new_token() returns text
language sql volatile as $$
  select translate(encode(extensions.gen_random_bytes(18), 'base64'), '+/=', '-_')
$$;

create or replace function public.hash_token(p_token text) returns text
language sql immutable as $$
  select encode(extensions.digest(p_token, 'sha256'), 'hex')
$$;

