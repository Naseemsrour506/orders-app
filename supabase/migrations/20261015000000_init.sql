-- מריצים פעם אחת מה-SQL Editor כדי לקבל את הקישור של המנהל.
create or replace function public.bootstrap_manager(p_name text) returns text
language plpgsql security definer set search_path = public as $$
declare
  v_id uuid;
  v_token text := public.new_token();
begin
  if exists (select 1 from public.members where role = 'manager') then
    raise exception 'כבר קיים מנהל. כדי לקבל קישור חדש השתמשו ב-reset_manager_link';
  end if;
  insert into public.members (name, role) values (p_name, 'manager') returning id into v_id;
  insert into public.member_tokens (member_id, token_hash) values (v_id, public.hash_token(v_token));
  return v_token;
end;
$$;

-- למקרה שהמנהל איבד את הטלפון: מריצים מה-SQL Editor ומקבלים קישור חדש.
create or replace function public.reset_manager_link() returns text
language plpgsql security definer set search_path = public as $$
declare
  v_id uuid;
  v_token text := public.new_token();
begin
  select id into v_id from public.members where role = 'manager' order by created_at limit 1;
  if v_id is null then
    raise exception 'אין מנהל. השתמשו ב-bootstrap_manager';
  end if;
  delete from public.member_devices where member_id = v_id;
  insert into public.member_tokens (member_id, token_hash) values (v_id, public.hash_token(v_token))
  on conflict (member_id) do update set token_hash = excluded.token_hash, created_at = now();
  return v_token;
end;
$$;

-- הטלפון פותח קישור: הכניסה האנונימית שלו נקשרת למשתמש של הקישור.
create or replace function public.claim_invite(p_token text) returns json
language plpgsql security definer set search_path = public as $$
declare
  v_member public.members;
begin
  if auth.uid() is null then
    raise exception 'אין כניסה' using errcode = '28000';
  end if;
  select m.* into v_member
  from public.member_tokens t
  join public.members m on m.id = t.member_id
  where t.token_hash = public.hash_token(p_token) and m.active;
  if v_member.id is null then
    raise exception 'הקישור לא תקף. בקשו מהמנהל קישור חדש' using errcode = '28000';
  end if;
  insert into public.member_devices (auth_uid, member_id) values (auth.uid(), v_member.id)
  on conflict (auth_uid) do update set member_id = excluded.member_id, last_seen_at = now();
  return json_build_object('id', v_member.id, 'name', v_member.name, 'role', v_member.role, 'team_id', v_member.team_id);
end;
$$;

create or replace function public.whoami() returns json
language plpgsql security definer set search_path = public as $$
declare
  v_member public.members;
begin
  select m.* into v_member
  from public.member_devices d
  join public.members m on m.id = d.member_id
  where d.auth_uid = auth.uid() and m.active;
  if v_member.id is null then
    return null;
  end if;
  update public.member_devices set last_seen_at = now() where auth_uid = auth.uid();
  return json_build_object('id', v_member.id, 'name', v_member.name, 'role', v_member.role, 'team_id', v_member.team_id);
end;
$$;

create or replace function public.create_member(p_name text, p_role public.member_role, p_team_id smallint default null)
returns json
language plpgsql security definer set search_path = public as $$
declare
  v_id uuid;
  v_token text := public.new_token();
begin
  perform public.require_manager();
  insert into public.members (name, role, team_id)
  values (trim(p_name), p_role, case when p_role = 'field' then p_team_id end)
  returning id into v_id;
  insert into public.member_tokens (member_id, token_hash) values (v_id, public.hash_token(v_token));
  return json_build_object('id', v_id, 'token', v_token);
end;
$$;

-- קישור חדש: הקודם מפסיק לעבוד מיד בכל הטלפונים.
create or replace function public.reset_member_link(p_member_id uuid) returns text
language plpgsql security definer set search_path = public as $$
declare
  v_token text := public.new_token();
begin
  perform public.require_manager();
  if not exists (select 1 from public.members where id = p_member_id) then
    raise exception 'משתמש לא נמצא';
  end if;
  delete from public.member_devices where member_id = p_member_id and auth_uid <> auth.uid();
  insert into public.member_tokens (member_id, token_hash) values (p_member_id, public.hash_token(v_token))
  on conflict (member_id) do update set token_hash = excluded.token_hash, created_at = now();
  return v_token;
end;
$$;

create or replace function public.set_member_active(p_member_id uuid, p_active boolean) returns void
language plpgsql security definer set search_path = public as $$
begin
  if public.require_manager() = p_member_id and not p_active then
    raise exception 'אי אפשר לחסום את עצמך';
  end if;
  update public.members set active = p_active where id = p_member_id;
  if not p_active then
    delete from public.member_devices where member_id = p_member_id;
    delete from public.push_subscriptions where member_id = p_member_id;
  end if;
end;
$$;

