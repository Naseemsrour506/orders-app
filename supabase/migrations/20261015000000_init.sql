create or replace function public.path_order_id(p_name text) returns bigint
language sql immutable as $$
  select case when split_part(p_name, '/', 1) = 'orders' and split_part(p_name, '/', 2) ~ '^[0-9]+$'
              then split_part(p_name, '/', 2)::bigint end
$$;

create or replace function public.can_read_file(p_name text) returns boolean
language sql stable security definer set search_path = public as $$
  select case
    when public.is_manager() then true
    when public.is_designer() then public.designer_can_see(public.path_order_id(p_name))
    when public.current_role_name() = 'field' then exists (
      select 1 from public.orders o
      where o.id = public.path_order_id(p_name)
        and o.team_id = public.current_team_id()
        and o.status in ('approved', 'done')
        and (o.final_file_path = p_name or o.done_photo_path = p_name)
    )
    else false
  end
$$;

create or replace function public.can_write_file(p_name text) returns boolean
language sql stable security definer set search_path = public as $$
  select case
    when public.is_manager() then public.path_order_id(p_name) is not null
    when public.is_designer() then public.designer_can_see(public.path_order_id(p_name))
    when public.current_role_name() = 'field' then
      split_part(p_name, '/', 3) = 'done' and public.field_can_touch(public.path_order_id(p_name))
    else false
  end
$$;

grant execute on function public.path_order_id(text), public.can_read_file(text), public.can_write_file(text) to authenticated;

create policy files_read on storage.objects for select to authenticated
  using (bucket_id = 'files' and public.can_read_file(name));

create policy files_write on storage.objects for insert to authenticated
  with check (bucket_id = 'files' and public.can_write_file(name));

