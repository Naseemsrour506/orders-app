create or replace function public.send_to_designer(p_order_id bigint) returns void
language plpgsql security definer set search_path = public as $$
declare
  v_status public.order_status;
begin
  perform public.require_manager();
  select status into v_status from public.orders where id = p_order_id for update;
  if v_status is null then
    raise exception 'הזמנה לא נמצאה';
  end if;
  if v_status not in ('new', 'review') then
    raise exception 'ההזמנה כבר אצל הגרפיקאי או בשלב מאוחר יותר';
  end if;
  update public.orders
  set status = 'design', sent_to_designer_at = coalesce(sent_to_designer_at, now())
  where id = p_order_id;
  perform public.system_message(p_order_id, 'נשלח לגרפיקאי');
  perform public.add_event(p_order_id, 'sent_to_designer');
end;
$$;

create or replace function public.return_for_fix(p_order_id bigint, p_note text) returns void
language plpgsql security definer set search_path = public as $$
declare
  v_status public.order_status;
begin
  perform public.require_manager();
  select status into v_status from public.orders where id = p_order_id for update;
  if v_status not in ('review', 'design', 'approved') then
    raise exception 'אפשר להחזיר לתיקון רק הזמנה שנמצאת בעיצוב או ממתינה לאישור';
  end if;
  update public.orders set status = 'fix', team_id = null, scheduled_date = null, approved_at = null
  where id = p_order_id;
  if coalesce(trim(p_note), '') <> '' then
    insert into public.messages (order_id, author_id, kind, body)
    values (p_order_id, public.current_member_id(), 'text', trim(p_note));
  end if;
  perform public.system_message(p_order_id, 'הוחזר לתיקון');
  perform public.add_event(p_order_id, 'returned', p_note);
end;
$$;

create or replace function public.approve_order(
  p_order_id bigint,
  p_team_id smallint,
  p_scheduled_date date,
  p_address text default null,
  p_field_notes text default null
) returns void
language plpgsql security definer set search_path = public as $$
declare
  v_status public.order_status;
  v_team text;
begin
  perform public.require_manager();
  select status into v_status from public.orders where id = p_order_id for update;
  if v_status is null then
    raise exception 'הזמנה לא נמצאה';
  end if;
  if v_status = 'done' then
    raise exception 'ההזמנה כבר בוצעה';
  end if;
  select name into v_team from public.teams where id = p_team_id;
  if v_team is null then
    raise exception 'צריך לבחור צוות';
  end if;
  update public.orders
  set status = 'approved',
      team_id = p_team_id,
      scheduled_date = coalesce(p_scheduled_date, public.today_il()),
      approved_at = now(),
      address = coalesce(trim(p_address), address),
      field_notes = coalesce(trim(p_field_notes), field_notes),
      field_issue = ''
  where id = p_order_id;
  perform public.system_message(p_order_id,
    'אושר לביצוע · ' || v_team || ' · ' || to_char(coalesce(p_scheduled_date, public.today_il()), 'DD/MM'));
  perform public.add_event(p_order_id, 'approved', '', p_team_id);
end;
$$;

-- המנהל מעביר עבודה מאושרת לצוות או תאריך אחר.
create or replace function public.reschedule_order(p_order_id bigint, p_team_id smallint, p_scheduled_date date)
returns void
language plpgsql security definer set search_path = public as $$
declare
  v_old_team smallint;
  v_team text;
begin
  perform public.require_manager();
  select team_id into v_old_team from public.orders where id = p_order_id and status = 'approved' for update;
  if not found then
    raise exception 'אפשר לשנות תאריך רק לעבודה מאושרת שעוד לא בוצעה';
  end if;
  select name into v_team from public.teams where id = p_team_id;
  if v_team is null then
    raise exception 'צריך לבחור צוות';
  end if;
  update public.orders set team_id = p_team_id, scheduled_date = p_scheduled_date where id = p_order_id;
  perform public.system_message(p_order_id, 'הועבר ל' || v_team || ' · ' || to_char(p_scheduled_date, 'DD/MM'));
  if v_old_team is distinct from p_team_id or p_scheduled_date <= public.today_il() then
    perform public.add_event(p_order_id, 'approved', '', p_team_id);
  end if;
end;
$$;

create or replace function public.reopen_order(p_order_id bigint) returns void
language plpgsql security definer set search_path = public as $$
begin
  perform public.require_manager();
  update public.orders
  set status = 'approved', done_at = null, done_by = null,
      scheduled_date = greatest(coalesce(scheduled_date, public.today_il()), public.today_il())
  where id = p_order_id and status = 'done';
  if not found then
    raise exception 'אפשר לפתוח מחדש רק עבודה שבוצעה';
  end if;
  perform public.system_message(p_order_id, 'נפתח מחדש לביצוע');
end;
$$;

