-- מערכת ניהול הזמנות: סכמה ראשונה
-- כל ההרשאות נאכפות כאן, במסד הנתונים. האפליקציה רק מציגה.

create extension if not exists pgcrypto with schema extensions;

-- ---------------------------------------------------------------------------
-- טיפוסים
-- ---------------------------------------------------------------------------

create type public.member_role as enum ('manager', 'designer', 'field');

-- new: חדשה, אצל המנהל
-- design: בעבודה אצל הגרפיקאי
-- review: טיוטה ממתינה לאישור המנהל
-- fix: חזר לתיקון אצל הגרפיקאי
-- approved: מאושר לביצוע, ברשימת צוות השטח
-- done: בוצע
-- "עבר ליום הבא" אינו סטטוס שמור: הזמנה מאושרת שתאריך הביצוע שלה עבר מוצגת כ"מאתמול".
create type public.order_status as enum ('new', 'design', 'review', 'fix', 'approved', 'done');

create type public.message_kind as enum ('text', 'image', 'file', 'audio', 'draft', 'final', 'system');

-- ---------------------------------------------------------------------------
-- טבלאות
-- ---------------------------------------------------------------------------

create table public.teams (
  id smallint primary key,
  name text not null
);

insert into public.teams (id, name) values (1, 'צוות 1'), (2, 'צוות 2');

create table public.members (
  id uuid primary key default gen_random_uuid(),
  name text not null check (length(trim(name)) > 0),
  role public.member_role not null,
  team_id smallint references public.teams (id),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  constraint field_member_has_team check (role <> 'field' or team_id is not null)
);

-- הקישור האישי נשמר רק כגיבוב, בטבלה שאף משתמש לא יכול לקרוא.
create table public.member_tokens (
  member_id uuid primary key references public.members (id) on delete cascade,
  token_hash text not null unique,
  created_at timestamptz not null default now()
);

-- כל טלפון שפתח קישור מקבל כניסה אנונימית של Supabase, שנקשרת כאן למשתמש.
-- קישור של צוות שטח יכול להיות פתוח בכמה טלפונים.
create table public.member_devices (
  auth_uid uuid primary key,
  member_id uuid not null references public.members (id) on delete cascade,
  created_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now()
);

create index on public.member_devices (member_id);

create table public.orders (
  id bigint generated by default as identity (start with 1001) primary key,
  title text not null default '',
  client_name text not null default '',
  client_phone text not null default '',
  address text not null default '',
  field_notes text not null default '',
  status public.order_status not null default 'new',
  design_due date,
  scheduled_date date,
  team_id smallint references public.teams (id),
  urgent boolean not null default false,
  bumped_at timestamptz,
  sent_to_designer_at timestamptz,
  approved_at timestamptz,
  done_at timestamptz,
  done_by uuid references public.members (id),
  done_photo_path text,
  done_note text not null default '',
  field_issue text not null default '',
  final_file_path text,
  final_file_name text,
  created_by uuid references public.members (id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index on public.orders (status);
create index on public.orders (team_id, scheduled_date);

create table public.messages (
  id bigint generated always as identity primary key,
  order_id bigint not null references public.orders (id) on delete cascade,
  author_id uuid references public.members (id),
  kind public.message_kind not null default 'text',
  body text not null default '',
  file_path text,
  file_name text,
  mime text,
  size_bytes bigint,
  file_deleted_at timestamptz,
  created_at timestamptz not null default now()
);

create index on public.messages (order_id, created_at);

-- מי צריך לקבל התראה. נכתב רק על ידי הפונקציות כאן, ונקרא רק על ידי פונקציית ההתראות.
create table public.events (
  id bigint generated always as identity primary key,
  order_id bigint references public.orders (id) on delete cascade,
  kind text not null,
  actor_id uuid references public.members (id),
  team_id smallint references public.teams (id),
  body text not null default '',
  created_at timestamptz not null default now(),
  notified_at timestamptz
);

create index on public.events (created_at) where notified_at is null;

create table public.push_subscriptions (
  endpoint text primary key,
  member_id uuid not null references public.members (id) on delete cascade,
  p256dh text not null,
  auth text not null,
  created_at timestamptz not null default now()
);

-- מפתחות VAPID להתראות. נוצרים לבד בקריאה הראשונה לפונקציית ההתראות.
create table public.app_secrets (
  key text primary key,
  value text not null
);

