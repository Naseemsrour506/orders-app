create or replace function public.field_tasks(p_team_id smallint default null)
returns table (
  id bigint,
  title text,
  client_name text,
  client_phone text,
  address text,
  field_notes text,
  scheduled_date date,
  urgent boolean,
  bumped_at timestamptz,
  carried boolean,
  done boolean,
  done_at timestamptz,
  done_photo_path text,
  field_issue text,
  final_file_path text,
  final_file_name text,
  team_id smallint
)
language plpgsql stable security definer set search_path = public as $$
declare
  v_team smallint;
  v_today date := public.today_il();
begin
  if public.is_manager() then
    v_team := p_team_id;
  elsif public.current_role_name() = 'field' then
    v_team := public.current_team_id();
  else
    raise exception 'אין הרשאה' using errcode = '42501';
  end if;

  return query
  select o.id, o.title, o.client_name, o.client_phone, o.address, o.field_notes, o.scheduled_date, o.urgent,
         o.bumped_at,
         (o.status = 'approved' and o.scheduled_date < v_today) as carried,
         (o.status = 'done') as done,
         o.done_at, o.done_photo_path, o.field_issue,
         case when o.final_file_name is not null and not exists (
           select 1 from public.messages fm
           where fm.order_id = o.id and fm.file_path = o.final_file_path and fm.file_deleted_at is not null
         ) then o.final_file_path end,
         o.final_file_name, o.team_id
  from public.orders o
  where (v_team is null or o.team_id = v_team)
    and (
      (o.status = 'approved' and o.scheduled_date <= v_today)
      or (o.status = 'done' and (o.done_at at time zone 'Asia/Jerusalem')::date = v_today)
    )
  order by
    (o.status = 'done'),
    (o.status = 'approved' and o.scheduled_date < v_today) desc,
    o.scheduled_date asc,
    o.urgent desc,
    o.bumped_at desc nulls last,
    o.approved_at asc;
end;
$$;

create or replace function public.field_can_touch(p_order_id bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select public.current_role_name() = 'field' and exists (
    select 1 from public.orders o
    where o.id = p_order_id and o.team_id = public.current_team_id() and o.status in ('approved', 'done')
  )
$$;

create or replace function public.field_mark_done(p_order_id bigint, p_photo_path text default null, p_note text default '')
returns void
language plpgsql security definer set search_path = public as $$
declare
  v_team smallint;
begin
  if not (public.field_can_touch(p_order_id) or public.is_manager()) then
    raise exception 'אין הרשאה' using errcode = '42501';
  end if;
  update public.orders
  set status = 'done', done_at = now(), done_by = public.current_member_id(),
      done_photo_path = coalesce(p_photo_path, done_photo_path),
      done_note = coalesce(p_note, ''), field_issue = ''
  where id = p_order_id and status = 'approved'
  returning team_id into v_team;
  if not found then
    return; -- כבר סומן (למשל סנכרון כפול מהטלפון)
  end if;
  if p_photo_path is not null then
    insert into public.messages (order_id, author_id, kind, body, file_path, file_name, mime)
    values (p_order_id, public.current_member_id(), 'image', coalesce(p_note, ''), p_photo_path, 'תמונת סיום.jpg', 'image/jpeg');
  end if;
  perform public.system_message(p_order_id, 'בוצע ✓' || case when coalesce(p_note, '') <> '' and p_photo_path is null then ' · ' || p_note else '' end);
  perform public.add_event(p_order_id, 'done', p_note, v_team);
end;
$$;

-- סימון בטעות: צוות השטח יכול לבטל "בוצע" באותו יום.
create or replace function public.field_undo_done(p_order_id bigint) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not (public.field_can_touch(p_order_id) or public.is_manager()) then
    raise exception 'אין הרשאה' using errcode = '42501';
  end if;
  update public.orders
  set status = 'approved', done_at = null, done_by = null
  where id = p_order_id and status = 'done'
    and (done_at at time zone 'Asia/Jerusalem')::date = public.today_il();
  if found then
    perform public.system_message(p_order_id, 'סימון "בוצע" בוטל');
  end if;
end;
$$;

create or replace function public.field_report_issue(p_order_id bigint, p_note text) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.field_can_touch(p_order_id) then
    raise exception 'אין הרשאה' using errcode = '42501';
  end if;
  if coalesce(trim(p_note), '') = '' then
    raise exception 'כתבו מה קרה';
  end if;
  update public.orders set field_issue = trim(p_note) where id = p_order_id;
  insert into public.messages (order_id, author_id, kind, body)
  values (p_order_id, public.current_member_id(), 'text', '⚠ מהשטח: ' || trim(p_note));
  perform public.add_event(p_order_id, 'field_issue', p_note);
end;
$$;

