create or replace function public.create_order(
  p_title text,
  p_client_name text default '',
  p_client_phone text default '',
  p_address text default '',
  p_design_due date default null
) returns bigint
language plpgsql security definer set search_path = public as $$
declare
  v_me uuid := public.require_manager();
  v_id bigint;
begin
  insert into public.orders (title, client_name, client_phone, address, design_due, created_by)
  values (coalesce(trim(p_title), ''), coalesce(trim(p_client_name), ''), coalesce(trim(p_client_phone), ''),
